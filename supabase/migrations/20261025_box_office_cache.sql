-- ERD.md의 세 테이블만 생성한다. 원본 응답 보관용 컬럼/테이블은 추가하지 않는다.
create table if not exists public.movies (
  movie_cd text primary key,
  movie_nm text not null,
  open_dt date,
  constraint movies_cd_nonblank check (length(btrim(movie_cd)) > 0),
  constraint movies_nm_nonblank check (length(btrim(movie_nm)) > 0)
);

create table if not exists public.box_office_periods (
  period_id bigint generated by default as identity primary key,
  period_type text not null,
  target_date date not null,
  range_start date not null,
  range_end date not null,
  status text not null,
  fetched_at timestamptz not null,
  expires_at timestamptz not null,
  constraint box_office_periods_type_check check (period_type in ('daily', 'weekly', 'weekend')),
  constraint box_office_periods_status_check check (status in ('data', 'empty')),
  constraint box_office_periods_range_check check (range_start <= range_end),
  constraint box_office_periods_daily_range_check check (period_type <> 'daily' or (range_start = target_date and range_end = target_date)),
  constraint box_office_periods_expiry_check check (expires_at > fetched_at),
  constraint box_office_periods_type_date_key unique (period_type, target_date)
);

create table if not exists public.box_office_results (
  period_id bigint not null references public.box_office_periods(period_id) on delete cascade,
  movie_cd text not null references public.movies(movie_cd) on delete restrict,
  rank integer not null check (rank > 0),
  sales_amt bigint not null,
  audi_cnt bigint not null,
  sales_acc bigint not null,
  audi_acc bigint not null,
  primary key (period_id, movie_cd)
);

create index if not exists box_office_results_period_rank_idx
  on public.box_office_results(period_id, rank);
create index if not exists box_office_results_movie_period_idx
  on public.box_office_results(movie_cd, period_id);

-- 브라우저/익명 사용자에게 직접 테이블 접근을 허용하지 않는다.
alter table public.movies enable row level security;
alter table public.box_office_periods enable row level security;
alter table public.box_office_results enable row level security;
revoke all on public.movies, public.box_office_periods, public.box_office_results
  from public, anon, authenticated, service_role;
revoke all on sequence public.box_office_periods_period_id_seq
  from public, anon, authenticated, service_role;

create or replace function public.read_box_office_period(
  p_period_type text,
  p_target_date date
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_period public.box_office_periods%rowtype;
  v_items jsonb;
begin
  if p_period_type not in ('daily', 'weekly', 'weekend') or p_target_date is null then
    raise exception 'INVALID_INPUT';
  end if;

  select * into v_period
  from public.box_office_periods
  where period_type = p_period_type and target_date = p_target_date;
  if not found then return null; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'movieCd', m.movie_cd,
    'movieNm', m.movie_nm,
    'openDt', m.open_dt,
    'rank', r.rank,
    'salesAmt', r.sales_amt::text,
    'audiCnt', r.audi_cnt::text,
    'salesAcc', r.sales_acc::text,
    'audiAcc', r.audi_acc::text
  ) order by r.rank, m.movie_cd), '[]'::jsonb)
  into v_items
  from public.box_office_results r
  join public.movies m on m.movie_cd = r.movie_cd
  where r.period_id = v_period.period_id;

  return jsonb_build_object(
    'status', v_period.status,
    'date', v_period.target_date,
    'type', v_period.period_type,
    'rangeStart', v_period.range_start,
    'rangeEnd', v_period.range_end,
    'fetchedAt', v_period.fetched_at,
    'expiresAt', v_period.expires_at,
    'items', v_items
  );
end;
$$;

create or replace function public.save_box_office_period(
  p_period_type text,
  p_target_date date,
  p_range_start date,
  p_range_end date,
  p_status text,
  p_request_started_at timestamptz,
  p_fetched_at timestamptz,
  p_expires_at timestamptz,
  p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_period_id bigint;
  v_existing_fetched_at timestamptz;
  v_item jsonb;
  v_count integer;
  v_actual_count integer;
begin
  if p_period_type not in ('daily', 'weekly', 'weekend')
     or p_status not in ('data', 'empty')
     or p_target_date is null or p_range_start is null or p_range_end is null
     or p_request_started_at is null or p_fetched_at is null or p_expires_at is null
     or p_range_start > p_range_end
     or (p_period_type = 'daily' and (p_range_start <> p_target_date or p_range_end <> p_target_date))
     or p_request_started_at > p_fetched_at or p_expires_at <= p_fetched_at
     or p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'INVALID_INPUT';
  end if;
  v_count := jsonb_array_length(p_items);
  if (p_status = 'empty' and v_count <> 0) or (p_status = 'data' and v_count = 0) then
    raise exception 'INVALID_STATUS';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_items) e
    where jsonb_typeof(e) <> 'object'
       or coalesce(length(btrim(e->>'movieCd')), 0) = 0
       or coalesce(length(btrim(e->>'movieNm')), 0) = 0
       or coalesce(e->>'rank', '') !~ '^[0-9]+$'
       or coalesce(e->>'salesAmt', '') !~ '^-?[0-9]+$'
       or coalesce(e->>'audiCnt', '') !~ '^-?[0-9]+$'
       or coalesce(e->>'salesAcc', '') !~ '^-?[0-9]+$'
       or coalesce(e->>'audiAcc', '') !~ '^-?[0-9]+$'
  ) or (
    select count(distinct e->>'movieCd') from jsonb_array_elements(p_items) e
  ) <> v_count then
    raise exception 'INVALID_ITEMS';
  end if;

  -- 동일 기간 저장은 한 번에 하나씩 진행한다. 트랜잭션 종료와 함께 잠금 해제.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtext(p_period_type), pg_catalog.hashtext(p_target_date::text)
  );
  select fetched_at into v_existing_fetched_at
  from public.box_office_periods
  where period_type = p_period_type and target_date = p_target_date
  for update;
  -- 더 늦게 시작한 요청이 먼저 저장됐거나 같은 시각/그 이후의 데이터가 있으면 덮어쓰지 않는다.
  if found and (v_existing_fetched_at > p_request_started_at or v_existing_fetched_at >= p_fetched_at) then
    return jsonb_build_object('saved', false, 'reason', 'STALE');
  end if;

  -- ① 영화. 개봉일이 빈 신규 응답은 기존 유효 개봉일을 지우지 않는다.
  for v_item in select value from jsonb_array_elements(p_items) loop
    insert into public.movies(movie_cd, movie_nm, open_dt)
    values (
      v_item->>'movieCd', v_item->>'movieNm',
      nullif(v_item->>'openDt', '')::date
    )
    on conflict (movie_cd) do update set
      movie_nm = excluded.movie_nm,
      open_dt = coalesce(excluded.open_dt, public.movies.open_dt);
  end loop;

  -- ② 조회 기간. 응답과 TTL은 함께 교체한다.
  insert into public.box_office_periods(
    period_type, target_date, range_start, range_end, status, fetched_at, expires_at
  ) values (
    p_period_type, p_target_date, p_range_start, p_range_end, p_status, p_fetched_at, p_expires_at
  )
  on conflict (period_type, target_date) do update set
    range_start = excluded.range_start,
    range_end = excluded.range_end,
    status = excluded.status,
    fetched_at = excluded.fetched_at,
    expires_at = excluded.expires_at
  returning period_id into v_period_id;

  -- ③ 실적. 이전 Top 10을 모두 지워 누락 영화가 남지 않도록 새 목록으로 교체한다.
  delete from public.box_office_results where period_id = v_period_id;
  insert into public.box_office_results(
    period_id, movie_cd, rank, sales_amt, audi_cnt, sales_acc, audi_acc
  )
  select v_period_id, e->>'movieCd', (e->>'rank')::integer,
    (e->>'salesAmt')::bigint, (e->>'audiCnt')::bigint,
    (e->>'salesAcc')::bigint, (e->>'audiAcc')::bigint
  from jsonb_array_elements(p_items) e;

  -- 커밋 전에 저장본을 입력과 대조한다. 어긋나면 예외로 전체 함수가 롤백된다.
  select count(*) into v_actual_count
  from public.box_office_results where period_id = v_period_id;
  if v_actual_count <> v_count or exists (
    select 1
    from jsonb_array_elements(p_items) e
    left join public.box_office_results r
      on r.period_id = v_period_id and r.movie_cd = e->>'movieCd'
    left join public.movies m on m.movie_cd = r.movie_cd
    where r.movie_cd is null or m.movie_cd is null
       or m.movie_nm <> e->>'movieNm'
       or (nullif(e->>'openDt', '') is not null and m.open_dt is distinct from (e->>'openDt')::date)
       or r.rank::text <> e->>'rank'
       or r.sales_amt::text <> e->>'salesAmt'
       or r.audi_cnt::text <> e->>'audiCnt'
       or r.sales_acc::text <> e->>'salesAcc'
       or r.audi_acc::text <> e->>'audiAcc'
  ) then
    raise exception 'SAVE_VERIFY_FAILED';
  end if;

  return jsonb_build_object('saved', true);
end;
$$;

-- SECURITY DEFINER 함수는 소유자가 테이블을 읽고/쓴다. 실행권은 서버 역할에만 준다.
revoke all on function public.read_box_office_period(text, date)
  from public, anon, authenticated;
revoke all on function public.save_box_office_period(text, date, date, date, text, timestamptz, timestamptz, timestamptz, jsonb)
  from public, anon, authenticated;
grant execute on function public.read_box_office_period(text, date) to service_role;
grant execute on function public.save_box_office_period(text, date, date, date, text, timestamptz, timestamptz, timestamptz, jsonb) to service_role;

notify pgrst, 'reload schema';
